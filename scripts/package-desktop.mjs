import { packager } from '@electron/packager';
import { cp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';
execFileSync(process.execPath,['scripts/build-native-audio.mjs'],{stdio:'inherit'});
const root=process.cwd();
const source=join(root,'work','desktop-package');
const destination=resolve(process.env.WOMP_DESKTOP_OUTPUT || join(root,'work','desktop-dist'));
if(!existsSync(join(root,'.next/standalone/server.js'))) throw new Error('Run npm run build first.');
await rm(source,{recursive:true,force:true});
await mkdir(source,{recursive:true});
await cp(join(root,'.next/standalone'),join(source,'runtime'),{recursive:true});
await cp(join(root,'node_modules/@img'),join(source,'runtime/node_modules/@img'),{recursive:true});
await cp(join(root,'.next/static'),join(source,'runtime/.next/static'),{recursive:true});
await cp(join(root,'public'),join(source,'runtime/public'),{recursive:true});
await mkdir(join(source,'seed'),{recursive:true});
for(const name of ['local-library.json','local-playlists.json','playlist-covers']) if(process.env.WOMP_INCLUDE_SEED==='1' && existsSync(join(root,'var',name))) await cp(join(root,'var',name),join(source,'seed',name),{recursive:true});
await cp(join(root,'desktop'),join(source,'desktop'),{recursive:true});
await cp(join(root,'scripts'),join(source,'scripts'),{recursive:true});
await writeFile(join(source,'package.json'),JSON.stringify({name:'womp-desktop',version:'0.1.0',productName:'.womp',main:'desktop/main.cjs',description:'Local music library and stage visuals',author:'Logan'}));
const iconset=join(root,'work','Womp.iconset');await mkdir(iconset,{recursive:true});
const svg=await readFile(join(root,'src/app/icon.svg'));
for(const size of [16,32,128,256,512]) for(const scale of [1,2]) await sharp(svg).resize(size*scale,size*scale).png().toFile(join(iconset,`icon_${size}x${size}${scale===2?'@2x':''}.png`));
const icon=join(root,'work','Womp.icns');execFileSync('iconutil',['-c','icns',iconset,'-o',icon]);
const electron=JSON.parse(await readFile(join(root,'node_modules/electron/package.json'),'utf8'));
const paths=await packager({dir:source,out:destination,name:'Womp',platform:'darwin',arch:process.arch,electronVersion:electron.version,icon,overwrite:true,asar:false,prune:false,appBundleId:'com.logan.womp',appCategoryType:'public.app-category.music',extendInfo:{CFBundleDisplayName:'.womp',NSMicrophoneUsageDescription:'Optional future recording workflows require your permission.'}});
console.log(paths.join('\n'));
